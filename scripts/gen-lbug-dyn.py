#!/usr/bin/env python3
"""Generate c/lbug_dyn.h: runtime-loaded pointers for every Ladybug C function
the shim uses. Run after changing the shim: python3 scripts/gen-lbug-dyn.py"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
shim = (root / "c" / "lbug_shim.c").read_text()
types = {"lbug_state", "lbug_database", "lbug_connection", "lbug_prepared_statement", "lbug_query_result",
         "lbug_flat_tuple", "lbug_value", "lbug_logical_type", "lbug_internal_id_t", "lbug_date_t",
         "lbug_timestamp_t", "lbug_timestamp_ns_t", "lbug_timestamp_ms_t", "lbug_timestamp_sec_t",
         "lbug_timestamp_tz_t", "lbug_interval_t", "lbug_int128_t", "lbug_system_config", "lbug_data_type_id",
         "lbug_query_summary"}
names = sorted({n for n in re.findall(r"\blbug_[a-z0-9_]+\b", shim)
                if not n.startswith("lbug_lean_") and n not in types and n.isidentifier() and not n.isupper()})
out = ["// Generated by scripts/gen-lbug-dyn.py; do not edit.",
       "// Pointers to the Ladybug C functions the shim uses, resolved at runtime from",
       "// the library file, so nothing links against liblbug.",
       "#pragma once", ""]
out += [f"static __typeof__(&{n}) p_{n} = NULL;" for n in names]
out += ["", "#define LBUG_DYN_FUNCS(X) \\"] + [f"    X({n}) \\" for n in names] + [""]
out += [f"#define {n} (*p_{n})" for n in names]
(root / "c" / "lbug_dyn.h").write_text("\n".join(out) + "\n")
print(f"{len(names)} functions")
